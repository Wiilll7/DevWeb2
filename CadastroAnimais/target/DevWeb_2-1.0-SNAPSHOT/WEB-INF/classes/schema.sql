-- Esquema do banco (H2). Executado na inicialização da aplicação (CREATE ... IF NOT EXISTS).

-- Empresas (tenants). Mantidas DIRETAMENTE NO BANCO (não há tela de cadastro).
-- "conflitos": ids das empresas em conflito de interesses com esta, separados por vírgula (ex.: '2,5').
CREATE TABLE IF NOT EXISTS empresa (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL UNIQUE,
    conflitos VARCHAR(255) NOT NULL DEFAULT ''
);

-- Usuários (login único no sistema todo).
CREATE TABLE IF NOT EXISTS usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login      VARCHAR(50)  NOT NULL UNIQUE,
    nome       VARCHAR(100) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL
);

-- Vínculo usuário x empresa, com o perfil do usuário NAQUELA empresa.
CREATE TABLE IF NOT EXISTS usuario_empresa (
    usuario_id BIGINT      NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    empresa_id BIGINT      NOT NULL REFERENCES empresa(id) ON DELETE CASCADE,
    perfil     VARCHAR(10) NOT NULL CHECK (perfil IN ('COMUM', 'ADMIN')),
    PRIMARY KEY (usuario_id, empresa_id)
);

CREATE TABLE IF NOT EXISTS noticia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT        NOT NULL REFERENCES empresa(id) ON DELETE CASCADE,
    autor_id        BIGINT        NOT NULL REFERENCES usuario(id),
    titulo          VARCHAR(150)  NOT NULL,
    texto           VARCHAR(4000) NOT NULL,
    data_publicacao TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT        NOT NULL REFERENCES empresa(id) ON DELETE CASCADE,
    descricao  VARCHAR(150)  NOT NULL,
    valor      DECIMAL(12,2) NOT NULL,
    vencimento DATE          NOT NULL,
    situacao   VARCHAR(10)   NOT NULL CHECK (situacao IN ('PENDENTE', 'PAGA'))
)
